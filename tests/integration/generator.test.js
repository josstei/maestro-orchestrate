'use strict';

const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const { ROOT, runGenerator, runGeneratorExpectFailure, withTempRepoCopy } = require('./helpers');
const { makeTempDir } = require('../support/fs');

function snapshotTree(root) {
  const snapshot = {};
  function visit(dir) {
    for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
      const file = path.join(dir, entry.name);
      const stat = fs.lstatSync(file);
      snapshot[path.relative(root, file)] = [stat.mode, stat.mtimeMs,
        entry.isDirectory() ? 'directory' : entry.isSymbolicLink() ? `symlink:${fs.readlinkSync(file)}`
          : createHash('sha256').update(fs.readFileSync(file)).digest('hex')];
      if (entry.isDirectory()) visit(file);
    }
  }
  visit(root);
  return snapshot;
}

const PUBLIC_ENTRYPOINTS = [
  'antigravity/mcp/maestro-server.js',
  'antigravity/hooks/hook-runner.js',
  'antigravity/hooks/policy-enforcer.js',
  'claude/mcp/maestro-server.js',
  'claude/scripts/hook-runner.js',
  'claude/scripts/policy-enforcer.js',
  'mcp/maestro-server.js',
  'hooks/hook-runner.js',
  'bin/maestro-mcp-server.js',
];

describe('generated public entrypoints', () => {
  it('recreates every missing public bootstrap with its existing loading behavior', () => {
    withTempRepoCopy('maestro-generator-entrypoints-', (repoRoot) => {
      for (const file of PUBLIC_ENTRYPOINTS) fs.unlinkSync(path.join(repoRoot, file));

      runGenerator([], { cwd: repoRoot });

      for (const file of PUBLIC_ENTRYPOINTS) {
        const actual = fs.readFileSync(path.join(repoRoot, file), 'utf8');
        assert.equal(actual, fs.readFileSync(path.join(ROOT, file), 'utf8'), file);
        assert.match(actual, /Generated by scripts\/generate\.js/);
      }
      if (process.platform !== 'win32') {
        assert.equal(fs.statSync(path.join(repoRoot, 'bin/maestro-mcp-server.js')).mode & 0o777, 0o755);
      }
    });
  });
});

describe('generator read-only modes', () => {
  it('--dry-run and --diff do not rewrite registry files even when registry content would change', () => {
    withTempRepoCopy('maestro-generator-read-only-', (repoRoot) => {
      const registryPath = path.join(repoRoot, 'src/generated/agent-registry.json');
      const before = fs.readFileSync(registryPath, 'utf8');

      for (const flag of ['--dry-run', '--diff']) {
        const agentName = `registry-${flag.slice(2)}-test`;
        fs.writeFileSync(
          path.join(repoRoot, `src/agents/${agentName}.md`),
          `---\nname: ${agentName}\n---\nBody\n`,
          'utf8'
        );

        runGenerator([flag], { cwd: repoRoot });

        assert.equal(
          fs.readFileSync(registryPath, 'utf8'),
          before,
          `Expected ${flag} to leave src/generated/agent-registry.json unchanged`
        );
      }
    });
  });

  it('previews fresh payload assets and stale removals without changing any files, modes or timestamps', () => {
    withTempRepoCopy('maestro-payload-read-only-', (repoRoot) => {
      fs.writeFileSync(path.join(repoRoot, 'src/hooks/logic/future-logic.js'), 'exports.handleFuture = () => ({});\n');
      fs.writeFileSync(path.join(repoRoot, 'plugins/maestro/src/obsolete.js'), 'obsolete\n');
      const before = snapshotTree(repoRoot);
      const dryRun = runGenerator(['--dry-run'], { cwd: repoRoot });
      assert.match(dryRun, /\[CREATE\] antigravity\/src\/hooks\/logic\/future-logic\.js/);
      assert.match(dryRun, /\[REMOVE\] plugins\/maestro\/src\/obsolete\.js/);
      assert.deepEqual(snapshotTree(repoRoot), before);
      const diff = runGenerator(['--diff'], { cwd: repoRoot });
      assert.match(diff, /\+\+\+ NEW: antigravity\/src\/hooks\/logic\/future-logic\.js/);
      assert.match(diff, /--- REMOVED: plugins\/maestro\/src\/obsolete\.js/);
      assert.deepEqual(snapshotTree(repoRoot), before);
    });
  });
});

describe('payload preflight', () => {
  it('rejects directories at file destinations before any write, clean or prune', () => {
    withTempRepoCopy('maestro-output-file-type-', (repoRoot) => {
      fs.appendFileSync(path.join(repoRoot, 'src/references/architecture.md'), '\nPending generated content\n');
      fs.writeFileSync(path.join(repoRoot, 'antigravity/src/obsolete.js'), 'must not be pruned\n');
      for (const relativePath of [
        'claude/src/references/architecture.md',
        'claude/mcp/maestro-server.js',
        'src/generated/agent-registry.json',
      ]) {
        const output = path.join(repoRoot, relativePath);
        const original = fs.readFileSync(output);
        fs.unlinkSync(output);
        fs.mkdirSync(output);
        fs.writeFileSync(path.join(output, 'sentinel'), 'must remain\n');
        const before = snapshotTree(repoRoot);
        for (const flags of [[], ['--clean'], ['--dry-run'], ['--diff']]) {
          assert.match(runGeneratorExpectFailure(flags, { cwd: repoRoot }).stderr, /Expected a regular file/);
          assert.deepEqual(snapshotTree(repoRoot), before);
        }
        fs.rmSync(output, { recursive: true });
        fs.writeFileSync(output, original);
      }
    });
  });

  it('rejects generated registry and output-directory symlinks before writing or pruning their targets', () => {
    withTempRepoCopy('maestro-payload-symlinks-', (repoRoot) => {
      const external = makeTempDir('maestro-payload-protected-');
      const target = path.join(external, 'registry.json');
      fs.writeFileSync(target, 'must not be overwritten\n');
      const registry = path.join(repoRoot, 'src/generated/agent-registry.json');
      const original = fs.readFileSync(registry, 'utf8');
      fs.unlinkSync(registry);
      fs.symlinkSync(target, registry);
      let before = snapshotTree(repoRoot);
      assert.match(runGeneratorExpectFailure([], { cwd: repoRoot }).stderr, /Symlink path is not allowed/);
      assert.deepEqual(snapshotTree(repoRoot), before);
      assert.equal(fs.readFileSync(target, 'utf8'), 'must not be overwritten\n');
      fs.unlinkSync(registry);
      fs.writeFileSync(registry, original);

      const output = path.join(repoRoot, 'claude/src');
      fs.rmSync(output, { recursive: true });
      fs.symlinkSync(external, output, 'dir');
      before = snapshotTree(repoRoot);
      assert.match(runGeneratorExpectFailure(['--clean'], { cwd: repoRoot }).stderr, /Symlink path is not allowed/);
      assert.deepEqual(snapshotTree(repoRoot), before);
      assert.deepEqual(fs.readdirSync(external), ['registry.json']);
    });
  });

  it('validates the last runtime before writing or pruning any earlier runtime, even with --clean', () => {
    withTempRepoCopy('maestro-payload-preflight-', (repoRoot) => {
      fs.appendFileSync(path.join(repoRoot, 'src/platforms/codex/runtime-config.js'), "\nif (false) require('./missing-payload-dependency');\n");
      fs.writeFileSync(path.join(repoRoot, 'antigravity/src/obsolete.js'), 'must remain\n');
      fs.unlinkSync(path.join(repoRoot, 'bin/maestro-mcp-server.js'));
      const before = snapshotTree(repoRoot);
      const failure = runGeneratorExpectFailure(['--clean'], { cwd: repoRoot });
      assert.match(failure.stderr, /Invalid codex payload dependencies/);
      assert.deepEqual(snapshotTree(repoRoot), before);
    });
  });

  it('copies the validated closure, removes stale payload files and stays unchanged on a second generation', () => {
    withTempRepoCopy('maestro-payload-apply-', (repoRoot) => {
      fs.writeFileSync(path.join(repoRoot, 'plugins/maestro/src/obsolete.js'), 'obsolete\n');
      runGenerator([], { cwd: repoRoot });
      assert.equal(fs.existsSync(path.join(repoRoot, 'plugins/maestro/src/obsolete.js')), false);
      for (const runtimeRoot of ['antigravity', 'claude', 'plugins/maestro']) {
        for (const script of ['ensure-workspace', 'read-active-session', 'read-setting', 'read-state', 'write-state']) {
          assert.equal(fs.readFileSync(path.join(repoRoot, runtimeRoot, `src/scripts/${script}.js`), 'utf8'),
            fs.readFileSync(path.join(repoRoot, `src/scripts/${script}.js`), 'utf8'));
        }
      }
      const before = snapshotTree(repoRoot);
      runGenerator([], { cwd: repoRoot });
      assert.deepEqual(snapshotTree(repoRoot), before);
    });
  });
});
