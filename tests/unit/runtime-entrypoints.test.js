'use strict';

const { describe, it } = require('node:test');
const assert = require('node:assert/strict');
const { buildRuntimeEntrypointOutputs } = require('../../src/generator/runtime-entrypoints');

const HEADER = "'use strict';\n// Generated by scripts/generate.js; edit src/generator/runtime-entrypoints.js.\n\n";

describe('buildRuntimeEntrypointOutputs', () => {
  it('renders the launchers a runtime config lists, without runtime-specific code', () => {
    const outputs = buildRuntimeEntrypointOutputs({
      root: { name: 'root', outputDir: './', launchers: { hookRunner: 'tools/hooks/run.js' } },
      bundled: { name: 'bundled', outputDir: 'hosts/bundled/', launchers: { mcpServer: 'server.js' } },
    });
    assert.deepEqual(outputs, [
      {
        outputPath: 'hosts/bundled/server.js',
        content: `${HEADER}const fs = require('node:fs');
const path = require('node:path');

const repoEntry = path.resolve(__dirname, '../../src/mcp/maestro-server.js');
const bundledEntry = path.resolve(__dirname, 'src/mcp/maestro-server.js');
require(fs.existsSync(repoEntry) ? repoEntry : bundledEntry).main();
`,
      },
      {
        outputPath: 'tools/hooks/run.js',
        content: `${HEADER}require('../../src/platforms/shared/hook-runner').main(process.argv[2], process.argv[3]);\n`,
      },
    ]);
  });

  it('rejects a launcher kind it cannot render', () => {
    assert.throws(
      () => buildRuntimeEntrypointOutputs({ root: { name: 'root', outputDir: './', launchers: { mcpServr: 'mcp.js' } } }),
      { message: 'Unknown launcher kind for root: "mcpServr"' }
    );
  });
});
