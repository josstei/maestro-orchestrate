'use strict';

const path = require('node:path');

const GENERATED_HEADER = '// Generated by scripts/generate.js; edit src/generator/runtime-entrypoints.js.\n';

/**
 * The launcher kinds a runtime config's `launchers` may list. Given the
 * runtime name, each names the canonical module it loads (relative to src/)
 * and the call that starts it. A package bin lives at the package root, not
 * in outputDir, is executable, and always loads the package's own src/.
 */
const LAUNCHER_KINDS = {
  mcpServer: () => ({ target: 'mcp/maestro-server.js', invocation: '.main()' }),
  hookRunner: () => ({ target: 'platforms/shared/hook-runner.js', invocation: '' }),
  policyEnforcer: (runtimeName) => ({ target: 'platforms/shared/policy-enforcer.js', invocation: `.main('${runtimeName}')` }),
  npmBin: () => ({ target: 'mcp/maestro-server.js', invocation: '.main()', packageBin: true }),
};

/**
 * Whether a runtime ships a detached copy of the source it loads. The runtime
 * rooted at the repo root (Qwen's extension dir) loads the repo's src/ itself.
 */
function hasDetachedPayload(runtime) {
  return runtime.outputDir !== './';
}

// Each launcher the runtime lists, with its output path from the package root.
function resolveLaunchers(runtime) {
  return Object.entries(runtime.launchers).map(([kind, launcherPath]) => {
    if (!LAUNCHER_KINDS[kind]) throw new Error(`Unknown launcher kind for ${runtime.name}: "${kind}"`);
    const launcher = LAUNCHER_KINDS[kind](runtime.name);
    return {
      ...launcher,
      outputPath: launcher.packageBin ? launcherPath : path.posix.join(runtime.outputDir, launcherPath),
    };
  });
}

/** The canonical modules that the runtime's launchers inside its outputDir load. */
function launcherTargets(runtime) {
  return resolveLaunchers(runtime).filter(({ packageBin }) => !packageBin).map(({ target }) => target);
}

// A launcher beside a detached payload loads the repo's src/ when it runs from
// a checkout and the bundled copy otherwise; any other launcher loads its
// package's src/ directly.
function renderLauncher(runtime, { outputPath, target, invocation, packageBin }) {
  const dirname = path.posix.dirname(outputPath);
  const repoEntry = path.posix.relative(dirname, `src/${target}`);
  if (!packageBin && hasDetachedPayload(runtime)) {
    const bundledEntry = path.posix.relative(dirname, path.posix.join(runtime.outputDir, 'src', target));
    return `const fs = require('node:fs');
const path = require('node:path');

const repoEntry = path.resolve(__dirname, '${repoEntry}');
const bundledEntry = path.resolve(__dirname, '${bundledEntry}');
require(fs.existsSync(repoEntry) ? repoEntry : bundledEntry)${invocation};
`;
  }
  const load = `require('${repoEntry.replace(/\.js$/, '')}')${invocation};\n`;
  if (!packageBin) return load;
  return `const path = require('node:path');

process.env.MAESTRO_EXTENSION_PATH =
  process.env.MAESTRO_EXTENSION_PATH || path.resolve(__dirname, '${path.posix.relative(dirname, '.')}');

${load}`;
}

// These paths are public host/package entrypoints. Keep their bootstrap code
// generated, without adding a runtime resolver that each install must ship.
function buildRuntimeEntrypointOutputs(runtimes) {
  const outputs = [];
  function add(outputPath, content, executable = false) {
    outputs.push({
      outputPath,
      content: `${executable ? '#!/usr/bin/env node\n' : ''}'use strict';\n${GENERATED_HEADER}\n${content}`,
      ...(executable ? { mode: 0o755 } : {}),
    });
  }

  for (const runtimeName of Object.keys(runtimes).sort()) {
    for (const launcher of resolveLaunchers(runtimes[runtimeName])) {
      add(launcher.outputPath, renderLauncher(runtimes[runtimeName], launcher), launcher.packageBin);
    }
  }
  return outputs;
}

module.exports = { buildRuntimeEntrypointOutputs, hasDetachedPayload, launcherTargets };
