'use strict';

const path = require('node:path');

const GENERATED_HEADER = '// Generated by scripts/generate.js; edit src/generator/runtime-entrypoints.js.\n';

// These paths are public host/package entrypoints. Keep their bootstrap code
// generated, without adding a runtime resolver that each install must ship.
function buildRuntimeEntrypointOutputs(runtimes) {
  const outputs = [];
  function add(outputPath, content, executable = false) {
    outputs.push({
      outputPath,
      content: `${executable ? '#!/usr/bin/env node\n' : ''}'use strict';\n${GENERATED_HEADER}\n${content}`,
      ...(executable ? { mode: 0o755 } : {}),
    });
  }

  for (const runtimeName of Object.keys(runtimes).sort()) {
    if (runtimeName === 'antigravity' || runtimeName === 'claude') {
      const root = runtimes[runtimeName].outputDir;
      const hookDir = runtimeName === 'claude' ? 'scripts' : 'hooks';
      const entries = [
        ['mcp/maestro-server.js', 'mcp/maestro-server.js', '.main()'],
        [`${hookDir}/hook-runner.js`, 'platforms/shared/hook-runner.js', ''],
        [`${hookDir}/policy-enforcer.js`, `platforms/${runtimeName}/policy-enforcer.js`, '.main()'],
      ];
      for (const [entry, target, invocation] of entries) {
        const outputPath = path.posix.join(root, entry);
        const dirname = path.posix.dirname(outputPath);
        const repoEntry = path.posix.relative(dirname, `src/${target}`);
        const bundledEntry = path.posix.relative(dirname, path.posix.join(root, 'src', target));
        add(outputPath, `const fs = require('node:fs');
const path = require('node:path');

const repoEntry = path.resolve(__dirname, '${repoEntry}');
const bundledEntry = path.resolve(__dirname, '${bundledEntry}');
require(fs.existsSync(repoEntry) ? repoEntry : bundledEntry)${invocation};
`);
      }
    } else if (runtimeName === 'qwen') {
      add('mcp/maestro-server.js', "require('../src/mcp/maestro-server').main();\n");
      add('hooks/hook-runner.js', "require('../src/platforms/shared/hook-runner');\n");
    } else if (runtimeName === 'codex') {
      add('bin/maestro-mcp-server.js', `const path = require('node:path');

process.env.MAESTRO_EXTENSION_PATH =
  process.env.MAESTRO_EXTENSION_PATH || path.resolve(__dirname, '..');

require('../src/mcp/maestro-server').main();
`, true);
    } else {
      throw new Error(`Unknown runtime for entrypoint generation: "${runtimeName}"`);
    }
  }
  return outputs;
}

module.exports = { buildRuntimeEntrypointOutputs };
